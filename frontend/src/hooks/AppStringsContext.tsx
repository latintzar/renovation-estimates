// =============================================================================
// CONTEXT
// =============================================================================

interface AppStringsContextValue {
  /** All translated strings — use s.keyName */
  s: AppStrings;
  /** Current language code */
  language: LanguageCode;
  /** Set language — triggers translation of ALL strings */
  setLanguage: (lang: LanguageCode) => void;
  /** True while a translation API call is in-flight */
  isTranslating: boolean;
  /** True when language is Spanish (source — no translation needed) */
  isSourceLanguage: boolean;
  /** Translate arbitrary text (for dynamic content like listing descriptions) */
  translateText: (text: string) => Promise<string>;
  /** Translate a batch of arbitrary texts */
  translateBatch: (texts: string[]) => Promise<string[]>;
  /** Translate listing-specific fields */
  translateListing: (data: { title?: string; description?: string; summary?: string; reasons?: string[] }) =>
    Promise<{ title?: string; description?: string; summary?: string; reasons?: string[] }>;
}

const AppStringsContext = createContext<AppStringsContextValue | null>(null);

// =============================================================================
// PROVIDER
// =============================================================================

export function AppStringsProvider({ children }: { children: React.ReactNode }) {
  const {
    language,
    setLanguage,
    translateBatch,
    translateText,
    translateListing,
    isTranslating,
    isSourceLanguage,
  } = useTranslation();

  const [strings, setStrings] = useState<AppStrings>({ ...DEFAULT_STRINGS });
  const translationInFlight = useRef(false);

  // When language changes, translate ALL strings in one batch
  useEffect(() => {
    if (isSourceLanguage) {
      setStrings({ ...DEFAULT_STRINGS });
      return;
    }

    // Prevent overlapping translation calls
    if (translationInFlight.current) return;
    translationInFlight.current = true;

    const translateAll = async () => {
      try {
        const keys = Object.keys(DEFAULT_STRINGS) as AppStringKey[];
        const overrides = MANUAL_OVERRIDES[language] || {};

        // Only send strings to the API that DON'T have manual overrides
        const keysToTranslate = keys.filter(k => !(k in overrides));
        const valuesToTranslate = keysToTranslate.map(k => DEFAULT_STRINGS[k]);

        const translated = valuesToTranslate.length > 0
          ? await translateBatch(valuesToTranslate)
          : [];

        // Build result: manual overrides first, then API translations
        const newStrings = { ...DEFAULT_STRINGS } as Record<string, string>;

        // Apply API translations
        keysToTranslate.forEach((key, i) => {
          if (translated[i]) newStrings[key] = translated[i];
        });

        // Apply manual overrides (these always win)
        for (const [key, value] of Object.entries(overrides)) {
          if (value) newStrings[key] = value;
        }

        setStrings(newStrings as unknown as AppStrings);
      } catch (err) {
        console.error('[AppStringsContext] Translation failed, keeping Spanish defaults:', err);
      } finally {
        translationInFlight.current = false;
      }
    };

    translateAll();
  }, [language, isSourceLanguage, translateBatch]);

  return (
    <AppStringsContext.Provider
      value={{
        s: strings,
        language,
        setLanguage,
        isTranslating,
        isSourceLanguage,
        translateText,
        translateBatch,
        translateListing,
      }}
    >
      {children}
    </AppStringsContext.Provider>
  );
}

// =============================================================================
// HOOK
// =============================================================================

/**
 * Access all translated UI strings and translation utilities.
 *
 * Usage:
 *   const { s, language, setLanguage, translateText } = useAppStrings();
 *   <h1>{s.reforma}</h1>
 */
export function useAppStrings(): AppStringsContextValue {
  const ctx = useContext(AppStringsContext);
  if (!ctx) {
    throw new Error('useAppStrings must be used within an <AppStringsProvider>');
  }
  return ctx;
}
