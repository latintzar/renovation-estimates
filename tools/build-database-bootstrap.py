#!/usr/bin/env python3
"""Assemble the fresh-install SQL from pinned retained DDL and current contracts."""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    "db/001_schema.sql",
    "supabase/migrations/007_property_intelligence_reports.sql",
    "supabase/migrations/007_due_diligence_research.sql",
    # 009 is the later comparable contract; 008 defines an incompatible predecessor.
    "supabase/migrations/009_comparables_tables.sql",
    "supabase/migrations/009_v048_tables.sql",
    "supabase/migrations/010_v05_schema_updates.sql",
    "supabase/migrations/011_v1_pipeline_schema.sql",
    "supabase/migrations/020_create_comparable_image_cache.sql",
    "supabase/migrations/021_add_casafari_raw_response_columns.sql",
    "backend/migrations/004_renovation_reports.sql",
    "db/bootstrap/current-contracts.sql",
    "supabase/migrations/0005_boq_line_items_provenance.sql",
    "backend/migrations/005_pipeline_run_status_source_of_truth.sql",
    "backend/migrations/009_gemini_call_log_and_run_costs_view.sql",
    "backend/migrations/010b_gemini_call_log_clear_history.sql",
    "backend/migrations/011_refresh_pipeline_run_status_remove_architect_report.sql",
    "supabase/migrations/202611010001_service_only_research_writes.sql",
    "db/bootstrap/private-backend.sql",
]

HEADER = """-- Generated by tools/build-database-bootstrap.py; see db/bootstrap/sources.json.
-- Fresh Supabase project only. This transaction preserves the historical migration files.
BEGIN;
SELECT pg_advisory_xact_lock(hashtext('renovation-estimates-fresh-bootstrap'));
DO $guard$
BEGIN
  IF to_regclass('auth.users') IS NULL THEN
    RAISE EXCEPTION 'Use a fresh Supabase project with its auth schema';
  END IF;
  IF EXISTS (
    SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace
    WHERE n.nspname='public' AND c.relkind IN ('r','p')
      AND NOT EXISTS (SELECT 1 FROM pg_depend d WHERE d.objid=c.oid AND d.deptype='e')
  ) THEN
    RAISE EXCEPTION 'Use a fresh project: public application tables already exist';
  END IF;
END;
$guard$;
"""


def outputs():
    parts = [HEADER]
    records = []
    for relative in SOURCES:
        raw = (ROOT / relative).read_bytes()
        text = raw.decode("utf-8")
        # One outer transaction; PL/pgSQL BEGIN blocks have no semicolon here.
        text = re.sub(r"(?im)^\s*(?:begin|commit);\s*$", "", text)
        if relative == "db/001_schema.sql":
            text = re.sub(r"(?m)^-- Project:.*$", "-- Original base schema; current contracts follow below.", text)
        text = "\n".join(line.rstrip() for line in text.splitlines())
        records.append({"path": relative, "sha256": hashlib.sha256(raw).hexdigest()})
        parts.extend(["\n-- SOURCE: " + relative + "\n", text.rstrip() + "\n"])
    parts.append("\nCOMMIT;\n")
    return "".join(parts), json.dumps({
        "scope": "Fresh native Estimate backend; provider acquisition and pricing datasets are separate inputs.",
        "historical_files_preserved": True,
        "sources_in_application_order": records,
        "normalizations": ["single outer transaction", "original project identifier removed", "trailing formatting whitespace removed in generated copy", "later comparable contract selected", "current queue/report/BOQ contracts added", "private service-role backend grants"],
    }, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
    args = parser.parse_args()
    sql, manifest = outputs()
    for relative, expected in [("db/bootstrap.sql", sql), ("db/bootstrap/sources.json", manifest)]:
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_text() != expected:
                parser.exit(1, relative + " needs regeneration\n")
        else:
            path.write_text(expected)
    print("Fresh-database SQL and source manifest verified" if args.check else "Fresh-database SQL and source manifest generated")


if __name__ == "__main__":
    main()
