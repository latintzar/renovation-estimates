def parse_price_range(price_str: str) -> Tuple[float, float, float]:
    """
    Parse a price string like "€15-€45, mid=€25" or "€600+, mid=€800"
    Returns: (low, mid, high)
    """
    # Handle open-ended luxury (€X+)
    if "+" in price_str:
        match = re.search(r'€([\d,.]+)\+', price_str)
        low = float(match.group(1).replace(",", "").replace(".", "")) if match else 0
        
        mid_match = re.search(r'mid=€([\d,.]+)', price_str)
        mid = float(mid_match.group(1).replace(",", "").replace(".", "")) if mid_match else low * 1.5
        
        return (low, mid, None)  # Open-ended high
    
    # Normal range: €X-€Y, mid=€Z
    range_match = re.search(r'€([\d,.]+)\s*[-–]\s*€?([\d,.]+)', price_str)
    if range_match:
        low = float(range_match.group(1).replace(",", "").replace(".", ""))
        high = float(range_match.group(2).replace(",", "").replace(".", ""))
    else:
        # Single value
        single_match = re.search(r'€([\d,.]+)', price_str)
        low = float(single_match.group(1).replace(",", "").replace(".", "")) if single_match else 0
        high = low * 1.5
    
    mid_match = re.search(r'mid=€([\d,.]+)', price_str)
    mid = float(mid_match.group(1).replace(",", "").replace(".", "")) if mid_match else (low + high) / 2
    
    return (low, mid, high)


def parse_brands(brand_str: str) -> List[str]:
    """
    Parse brands from "Brands: IKEA, Leroy Merlin, Sklum"
    """
    if not brand_str:
        return []
    
    # Extract after "Brands:" or "|"
    brand_part = brand_str
    if "Brands:" in brand_str:
        brand_part = brand_str.split("Brands:")[-1]
    elif "|" in brand_str:
        brand_part = brand_str.split("|")[-1]
    
    # Clean and split
    brands = []
    for brand in brand_part.split(","):
        brand = brand.strip().strip("[]()\"'")
        if brand and len(brand) > 1:
            brands.append(brand)
    
    return brands[:5]  # Max 5 brands


def parse_item_block(block: str, current_category: str) -> Optional[ParsedFFEItem]:
    """
    Parse a single item block from the research file.
    """
    lines = block.strip().split("\n")
    
    # Initialize values
    item_data = {}
    
    for line in lines:
        line = line.strip()
        if not line:
            continue
        
        # Parse each field
        if line.startswith("ITEM:"):
            item_data["name_es"] = line.replace("ITEM:", "").strip()
        elif line.startswith("CODE:"):
            item_data["code"] = line.replace("CODE:", "").strip()
        elif line.startswith("DESCRIPTION_ES:"):
            item_data["description_es"] = line.replace("DESCRIPTION_ES:", "").strip()
        elif line.startswith("SPECS:"):
            item_data["typical_specs"] = line.replace("SPECS:", "").strip()
        elif line.startswith("BUDGET:"):
            parts = line.replace("BUDGET:", "").strip()
            low, mid, high = parse_price_range(parts)
            item_data["budget_low"] = low
            item_data["budget_mid"] = mid
            item_data["budget_high"] = high if high else low * 1.5
            item_data["brands_budget"] = parse_brands(parts)
        elif line.startswith("MID:"):
            parts = line.replace("MID:", "").strip()
            low, mid, high = parse_price_range(parts)
            item_data["mid_low"] = low
            item_data["mid_mid"] = mid
            item_data["mid_high"] = high if high else mid * 1.3
            item_data["brands_mid"] = parse_brands(parts)
        elif line.startswith("HIGH:"):
            parts = line.replace("HIGH:", "").strip()
            low, mid, high = parse_price_range(parts)
            item_data["high_low"] = low
            item_data["high_mid"] = mid
            item_data["high_high"] = high if high else mid * 1.3
            item_data["brands_high"] = parse_brands(parts)
        elif line.startswith("LUXURY:"):
            parts = line.replace("LUXURY:", "").strip()
            low, mid, high = parse_price_range(parts)
            item_data["luxury_low"] = low
            item_data["luxury_mid"] = mid
            item_data["luxury_high"] = high  # Can be None
            item_data["brands_luxury"] = parse_brands(parts)
        elif line.startswith("PRIORITY:"):
            priority = line.replace("PRIORITY:", "").strip().lower()
            if "alta" in priority or "high" in priority:
                item_data["investment_priority"] = "alta"
            elif "baja" in priority or "low" in priority:
                item_data["investment_priority"] = "baja"
            else:
                item_data["investment_priority"] = "media"
        elif line.startswith("LIFESPAN:"):
            lifespan_str = line.replace("LIFESPAN:", "").strip()
            match = re.search(r'(\d+)', lifespan_str)
            item_data["lifespan_years"] = int(match.group(1)) if match else 10
        elif line.startswith("BASIS:"):
            item_data["basis_notes"] = line.replace("BASIS:", "").strip()
    
    # Validate required fields
    if "code" not in item_data or "name_es" not in item_data:
        return None
    
    # Check for minimum pricing data
    if "budget_mid" not in item_data:
        return None
    
    # Map category
    category_code = CATEGORY_MAP.get(current_category, "DECOR")
    
    # Check if energy relevant
    energy_relevant = any(code in item_data["code"].upper() for code in ENERGY_CODES)
    
    # Create item
    try:
        return ParsedFFEItem(
            code=item_data["code"],
            category_code=category_code,
            subcategory_code=None,
            name_es=item_data.get("name_es", ""),
            name_en="",  # Will derive from Spanish name
            description_es=item_data.get("description_es", ""),
            typical_specs=item_data.get("typical_specs", ""),
            budget_low=item_data.get("budget_low", 0),
            budget_mid=item_data.get("budget_mid", 0),
            budget_high=item_data.get("budget_high", 0),
            mid_low=item_data.get("mid_low", 0),
            mid_mid=item_data.get("mid_mid", 0),
            mid_high=item_data.get("mid_high", 0),
            high_low=item_data.get("high_low", 0),
            high_mid=item_data.get("high_mid", 0),
            high_high=item_data.get("high_high", 0),
            luxury_low=item_data.get("luxury_low", 0),
            luxury_mid=item_data.get("luxury_mid"),
            luxury_high=item_data.get("luxury_high"),
            investment_priority=item_data.get("investment_priority", "media"),
            lifespan_years=item_data.get("lifespan_years", 10),
            energy_relevant=energy_relevant,
            brands_budget=item_data.get("brands_budget", []),
            brands_mid=item_data.get("brands_mid", []),
            brands_high=item_data.get("brands_high", []),
            brands_luxury=item_data.get("brands_luxury", []),
            basis_notes=item_data.get("basis_notes", f"Parsed from Gemini 3 Pro research - {current_category}"),
            source_year=2024
        )
    except Exception as e:
        print(f"Error creating item {item_data.get('code', 'UNKNOWN')}: {e}")
        return None


def parse_research_file(filepath: str) -> List[ParsedFFEItem]:
    """
    Parse the entire research file and extract all items.
    """
    with open(filepath, 'r', encoding='utf-8', errors='ignore') as f:
        content = f.read()
    
    items = []
    current_category = "UNKNOWN"
    
    # Find all MAIN category markers (format: "CATEGORY: XXX" at start of line or after ===)
    # NOT subcategory markers (which have "SUBCATEGORY:" or "###")
    main_category_pattern = r'^CATEGORY:\s*(\w+)'
    
    # Split content into lines to track position
    lines = content.split('\n')
    
    # Build a map of line number -> category
    line_to_category = {}
    for i, line in enumerate(lines):
        # Only match MAIN categories (CATEGORY: at line start, not SUBCATEGORY)
        if line.strip().startswith("CATEGORY:") and "SUBCATEGORY" not in line:
            match = re.search(r'CATEGORY:\s*(\w+)', line)
            if match:
                current_category = match.group(1)
                print(f"  Found main category: {current_category}")
        line_to_category[i] = current_category
    
    # Now split by item blocks (marked with ```)
    # Reset current_category
    current_category = "UNKNOWN"
    
    blocks = re.split(r'```', content)
    
    # Track position in original content
    position = 0
    
    for i, block in enumerate(blocks):
        # Find which line this block starts at
        block_start_pos = content.find(block, position)
        if block_start_pos >= 0:
            # Count newlines to find line number
            line_num = content[:block_start_pos].count('\n')
            
            # Get category for this line
            if line_num in line_to_category:
                current_category = line_to_category[line_num]
            
            position = block_start_pos + len(block)
        
        # Check if this block contains an item
        if "ITEM:" in block and "CODE:" in block:
            item = parse_item_block(block, current_category)
            if item:
                items.append(item)
    
    return items


