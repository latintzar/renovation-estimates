import argparse
import base64
import json
import logging
from pathlib import Path
from typing import Dict, List

import numpy as np
from PIL import Image

from pipeline.gemini_client import call_gemini
from pipeline.utils.glb_utils import GlbInfo, extract_positions, load_glb


logger = logging.getLogger(__name__)


def _sample_points(points: np.ndarray, max_points: int) -> np.ndarray:
    if points.shape[0] <= max_points:
        return points
    indices = np.random.choice(points.shape[0], size=max_points, replace=False)
    return points[indices]


def _render_depth_projection(
    points: np.ndarray,
    axis_x: int,
    axis_y: int,
    axis_depth: int,
    image_size: int,
) -> Image.Image:
    coords = points[:, [axis_x, axis_y, axis_depth]]
    xy = coords[:, :2]
    depth = coords[:, 2]

    min_xy = xy.min(axis=0)
    max_xy = xy.max(axis=0)
    span_xy = max_xy - min_xy
    if np.any(span_xy <= 0):
        raise RuntimeError("Degenerate projection span for rendering")

    norm_xy = (xy - min_xy) / span_xy
    px = np.clip((norm_xy[:, 0] * (image_size - 1)).round().astype(int), 0, image_size - 1)
    py = np.clip((norm_xy[:, 1] * (image_size - 1)).round().astype(int), 0, image_size - 1)

    depth_min = depth.min()
    depth_max = depth.max()
    depth_span = depth_max - depth_min if depth_max > depth_min else 1.0

    flat_index = py * image_size + px
    depth_buffer = np.full(image_size * image_size, np.inf, dtype=np.float32)
    np.minimum.at(depth_buffer, flat_index, depth)

    depth_buffer = depth_buffer.reshape((image_size, image_size))
    depth_buffer[~np.isfinite(depth_buffer)] = depth_max

    depth_norm = (depth_buffer - depth_min) / depth_span
    depth_img = (depth_norm * 255.0).clip(0, 255).astype(np.uint8)

    return Image.fromarray(depth_img, mode="L")


def _save_image(image: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    image.save(path, format="PNG")


def _image_to_base64(path: Path) -> Dict[str, str]:
    data = base64.b64encode(path.read_bytes()).decode("utf-8")
    return {"mime_type": "image/png", "data": data}


def _build_prompt(bbox: Dict[str, List[float]], notes: List[str]) -> str:
    notes_text = "\n".join(f"- {note}" for note in notes)
    return f"""
You are a senior indoor reconstruction specialist. Your task is to infer a coarse IndoorGML-lite layout from orthographic depth projections of a GLB mesh.

WHY THIS MATTERS for this task: We need a canonical, auditable indoor geometry model to drive renovation takeoffs (wall areas, openings, and rough room footprints). If the geometry is ambiguous, we still need a conservative envelope rather than guessing fine detail.

What you are seeing:
- The images are depth projections derived from mesh vertices only (no textures, no camera poses).
- Each image is an orthographic projection (top/front/side). Darker pixels are nearer; lighter pixels are farther.
- The GLB metadata suggests it was generated by trimesh; there are no cameras or textures in the file.

Mesh bounding box (units unknown, likely meters but do NOT assume unless it fits):
{json.dumps(bbox, indent=2)}

Notes:
{notes_text}

Questions to guide your reasoning:
- Where are the dominant vertical planes that look like walls?
- Does the envelope suggest multiple rooms or a single open space?
- If you cannot confidently split rooms, output a single room with low confidence.
- Are there any obvious openings (doors/windows) implied by gaps in wall massing?

Output requirements (valid JSON only, no markdown):
Your output should be a JSON object with:
- schema: string identifier like \"glb_indoorgml_probe@0.1\"
- rooms: list of rooms. Each room should include:
  - room_id, cluster_id, cluster_name
  - estimated_m2, estimated_dimensions {{length_m, width_m, aspect_ratio, dimension_confidence}}
  - estimated_height_m, perimeter_m
  - wall_segments: list with wall_id, length_m, height_m, features (list of tags), photo_indices (empty list)
  - openings: list with opening_id, opening_type, wall_id, width_m, height_m, sill_height_m, confidence, photo_indices (empty list), defaulted, notes
  - confidence, reasoning, assumptions (list of short strings)
- global_confidence: overall confidence
- scale_assumptions: object with unit_guess and rationale

If you cannot see enough evidence for openings, return an empty openings list.
Be conservative: prefer under-stating detail over inventing it.
"""


async def _run(args: argparse.Namespace) -> None:
    glb_path = Path(args.glb).resolve()
    out_dir = Path(args.out_dir).resolve()

    logger.info(f"Loading GLB | path={glb_path}")
    info = load_glb(glb_path)
    points = extract_positions(info)
    logger.info(f"Loaded positions | count={points.shape[0]:,}")

    min_xyz = points.min(axis=0)
    max_xyz = points.max(axis=0)
    size_xyz = max_xyz - min_xyz
    bbox = {
        "min_xyz": min_xyz.tolist(),
        "max_xyz": max_xyz.tolist(),
        "size_xyz": size_xyz.tolist(),
    }

    notes = [
        f"Meshes: {len(info.json_data.get('meshes', []))}",
        f"Nodes: {len(info.json_data.get('nodes', []))}",
        "No cameras found in GLB",
        "No textures found in GLB",
    ]

    sample_points = _sample_points(points, args.max_points)
    logger.info(f"Sampling points | sampled={sample_points.shape[0]:,}")

    top = _render_depth_projection(sample_points, axis_x=0, axis_y=1, axis_depth=2, image_size=args.image_size)
    front = _render_depth_projection(sample_points, axis_x=0, axis_y=2, axis_depth=1, image_size=args.image_size)
    side = _render_depth_projection(sample_points, axis_x=1, axis_y=2, axis_depth=0, image_size=args.image_size)

    top_path = out_dir / "glb_depth_top.png"
    front_path = out_dir / "glb_depth_front.png"
    side_path = out_dir / "glb_depth_side.png"

    _save_image(top, top_path)
    _save_image(front, front_path)
    _save_image(side, side_path)

    meta = {
        "glb_path": str(glb_path),
        "bbox": bbox,
        "notes": notes,
        "images": {
            "top": str(top_path),
            "front": str(front_path),
            "side": str(side_path),
        },
    }
    meta_path = out_dir / "glb_probe_meta.json"
    meta_path.write_text(json.dumps(meta, indent=2), encoding="utf-8")
    logger.info(f"Wrote probe metadata | path={meta_path}")

    if not args.run_gemini:
        logger.info("Skipping Gemini run (use --run-gemini to enable)")
        return

    images = [_image_to_base64(top_path), _image_to_base64(front_path), _image_to_base64(side_path)]
    prompt = _build_prompt(bbox=bbox, notes=notes)
    logger.info(f"Calling Gemini | model={args.model}")

    response = await call_gemini(
        prompt=prompt,
        model=args.model,
        temperature=0.2,
        max_tokens=8000,
        images=images,
        use_spanish=False,
    )
    if not response.success or not response.text:
        raise RuntimeError(f"Gemini call failed: {response.error}")

    output_path = out_dir / "glb_indoorgml_lite.json"
    output_path.write_text(response.text, encoding="utf-8")
    logger.info(f"Wrote Gemini output | path={output_path}")


def main() -> None:
    logging.basicConfig(level=logging.INFO)
    parser = argparse.ArgumentParser(description="Probe GLB file for IndoorGML-lite feasibility.")
    parser.add_argument("--glb", required=True, help="Path to GLB file")
    parser.add_argument("--out-dir", default="docs/reference/glb_probe", help="Output directory")
    parser.add_argument("--image-size", type=int, default=768, help="Projection image size (px)")
    parser.add_argument("--max-points", type=int, default=300000, help="Max sampled vertices for rendering")
    parser.add_argument("--run-gemini", action="store_true", help="Run Gemini on projections")
    parser.add_argument("--model", default="pro", help="Gemini model alias (pro|flash|flash-lite)")
    args = parser.parse_args()

    try:
        import asyncio

        asyncio.run(_run(args))
    except Exception:
        logger.exception("GLB probe failed")
        raise


if __name__ == "__main__":
    main()
