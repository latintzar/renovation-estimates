-- Global queue ordering remains in SQL; V5/GLA predecessor gating remains in
-- pipeline_worker.py. Expired jobs follow the retained reaper/explicit retry path.
CREATE FUNCTION public.claim_pipeline_jobs(
  p_worker_id text, p_limit integer DEFAULT 10, p_lock_seconds integer DEFAULT 300
) RETURNS SETOF public.pipeline_jobs LANGUAGE plpgsql SET search_path = pg_catalog,public AS $$
BEGIN
  IF p_worker_id IS NULL OR btrim(p_worker_id) = '' OR length(p_worker_id) > 200
     OR p_limit IS NULL OR p_limit < 1 OR p_limit > 100
     OR p_lock_seconds IS NULL OR p_lock_seconds < 1 OR p_lock_seconds > 3600 THEN
    RAISE EXCEPTION 'Supply a worker identity, limit 1..100 and lease 1..3600 seconds'
      USING ERRCODE = '22023';
  END IF;
  RETURN QUERY
    WITH selected AS (
      SELECT j.id FROM public.pipeline_jobs j
      WHERE j.status = 'queued' AND j.available_at <= now()
        AND j.attempts < j.max_attempts
      ORDER BY j.available_at,j.created_at,j.id
      LIMIT p_limit FOR UPDATE SKIP LOCKED
    )
    UPDATE public.pipeline_jobs j SET
      status = 'in_progress', attempts = j.attempts + 1,
      locked_by = p_worker_id,
      locked_until = now() + make_interval(secs => p_lock_seconds),
      last_heartbeat_at = now(), started_at = coalesce(j.started_at,now()),
      finished_at = NULL, updated_at = now()
    FROM selected WHERE j.id = selected.id RETURNING j.*;
END;
$$;
CREATE FUNCTION public.pipeline_job_counts(p_run_id text)
RETURNS TABLE(status text,count bigint) LANGUAGE sql STABLE
SET search_path = pg_catalog,public AS $$
  SELECT j.status,count(*) FROM public.pipeline_jobs j
  WHERE j.run_id = p_run_id GROUP BY j.status;
$$;

